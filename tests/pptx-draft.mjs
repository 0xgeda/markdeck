import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import JSZip from 'jszip';
import {createDraft,arrangePage} from '../src/presentation/draft.js';
import {exportPptx} from '../src/presentation/pptx.js';
const dom=new JSDOM('');
const source='# 项目报告\n\n整理时间：今天\n\n## 结论\n\n- 第一条\n- 第二条\n\n### 依据\n\n| 项目 | 金额 |\n| --- | --- |\n| 示例 | 123 |\n\n## 下一步\n\n原始内容';
const draft=createDraft(source,'项目报告');
assert.deepEqual(draft.pages.map(page=>page.title),['项目报告','结论','依据','下一步']);
assert.equal(draft.pages.length,4);
assert.match(draft.pages[2].body,/123/);
assert.equal(createDraft('# 标题\n\n```md\n## 代码中的标题\n---\n```\n\n## 实际页\n\n正文','测试').pages.length,2);
assert.equal(createDraft('# 标题\n\n甲\n\n---\n\n乙','测试').pages.length,2);
draft.pages[1].title='手动修改标题';draft.pages[1].body='确认后的文字';
const png='data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j5xkAAAAASUVORK5CYII=';
draft.pages.push({title:'图片页',body:`![截图](${png})`});
const data=await exportPptx(draft,dom.window.document);
const zip=await JSZip.loadAsync(Buffer.from(data,'base64'));
const files=Object.keys(zip.files).filter(name=>/^ppt\/slides\/slide\d+\.xml$/.test(name));assert.equal(files.length,5);
const second=await zip.file('ppt/slides/slide2.xml').async('string');assert.match(second,/手动修改标题/);assert.match(second,/确认后的文字/);assert.match(second,/<p:sp>/);assert.doesNotMatch(second,/<p:pic>/);
const third=await zip.file('ppt/slides/slide3.xml').async('string');assert.match(third,/<a:tbl>/);assert.match(third,/123/);
assert.match(await zip.file('ppt/slides/slide5.xml').async('string'),/<p:pic>/);
assert.ok(Object.keys(zip.files).some(name=>name.startsWith('ppt/media/')));
assert.match(source,/原始内容/);
const long={title:'过长',body:'很长的正文'.repeat(4000)};assert.equal(arrangePage(long,dom.window.document).overflow,true);
await assert.rejects(exportPptx({...draft,pages:[long]},dom.window.document),/拆分/);
dom.window.close();console.log('Draft pagination, fenced code, actual PPTX XML, editable text/table, embedded image, overflow protection passed.');
