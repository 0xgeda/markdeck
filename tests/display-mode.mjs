import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {enterDisplay} from '../src/display-mode.js';
const dom=new JSDOM('<input id="title"><dialog id="settings-dialog"></dialog><header class="topbar"></header><section contenteditable="true"><p>正文</p></section>');
globalThis.window=dom.window;
const document=window.document;document.querySelector('dialog').close=()=>{};
window.CSS={highlights:new Map()};window.Highlight=class{constructor(...ranges){this.ranges=ranges;}};
const editor={getEditorElements:()=>({wwEditor:document.body})};
const editable=document.querySelector('section');
window.scrollY=600;window.scrollTo=({top})=>{window.scrollY=top;};
document.querySelector('.topbar').getBoundingClientRect=()=>({bottom:72});
editable.querySelector('p').getBoundingClientRect=()=>{const top=(document.body.classList.contains('display-mode')?1200:900)-window.scrollY;return {top,bottom:top+100};};
enterDisplay(editor);enterDisplay(editor);
assert.equal(document.querySelectorAll('.display-exit').length,1);
assert.equal(editable.getAttribute('contenteditable'),'false');assert.equal(window.scrollY,900);assert.equal(editable.querySelector('p').getBoundingClientRect().top,300);
const range=document.createRange();range.selectNodeContents(editable);document.getSelection().removeAllRanges();document.getSelection().addRange(range);document.querySelector('[data-highlight]').click();assert.equal(window.CSS.highlights.size,1);assert.equal(editable.textContent,'正文');
document.dispatchEvent(new window.KeyboardEvent('keydown',{key:'Escape'}));
assert.equal(editable.getAttribute('contenteditable'),'true');assert.equal(window.scrollY,600);assert.equal(window.CSS.highlights.size,0);
assert.equal(editable.textContent,'正文');
assert.equal(document.body.classList.contains('display-mode'),false);
assert.equal(document.querySelector('#title').readOnly,false);
dom.window.close();console.log('Display mode preserves content, blocks editing, restores editing on Escape and prevents duplicate controls.');
